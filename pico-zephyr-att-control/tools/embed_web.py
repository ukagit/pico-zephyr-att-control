#!/usr/bin/env python3
"""Regenerate the embedded page; run after editing web/att.html."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
html = (root/'web/att.html').read_text()
assert html.count('@VERSION@') == 1
before, after = html.split('@VERSION@')
lines = ['/* Generated by tools/embed_web.py; edit web/att.html. */', 'static const char page[] =']
for part_index, part in enumerate((before, after)):
    if part_index:
        lines.append('HAMLAB_VERSION')
    lines.extend(json.dumps(line, ensure_ascii=False) for line in part.splitlines(keepends=True))
lines[-1] += ';'
(root/'src/att_web.h').write_text('\n'.join(lines)+'\n')
